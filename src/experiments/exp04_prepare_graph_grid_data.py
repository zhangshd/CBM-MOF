"""
Exp04 – Prepare MOFTransformer / CGCNN graph and grid data via SLURM.

Source: src/jupyter/4_prepare_graph_grid_data.ipynb

Steps
-----
1. Partition sampled CIFs into batches.
2. Generate one SLURM job script per batch that calls the data-prep tool.
3. Submit all scripts (or dry-run in --test mode).

Outputs (normal mode)
----------------------
src/moftransformer/data/round2/graphs_grids/   (generated by SLURM jobs)

Run
---
python src/experiments/exp04_prepare_graph_grid_data.py
python src/experiments/exp04_prepare_graph_grid_data.py --test
"""
import argparse
import math
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from utils import REPO_ROOT, add_test_arg, sbatch_submit, resolve_output_dir

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------
CIF_INPUT_DIR   = REPO_ROOT / "data" / "processed" / "stratified_datasets" / "cifs"
GRAPH_GRID_DIR  = REPO_ROOT / "src" / "moftransformer" / "data" / "round2" / "graphs_grids"
LOG_DIR_PROD    = GRAPH_GRID_DIR.parent / "logs"   # src/moftransformer/data/round2/logs
PREP_SCRIPT     = REPO_ROOT / "src" / "moftransformer" / "datamodule" / "prepare_data.py"
PARTITION       = "C9654"
N_CPUS          = 1
N_JOBS_TOTAL    = 300


# ---------------------------------------------------------------------------
# SLURM job template  (mirrors notebook cell 1 of 4_prepare_graph_grid_data.ipynb)
# ---------------------------------------------------------------------------
JOB_TEMPLATE = """\
#!/bin/bash
#SBATCH --job-name={job_name}
#SBATCH --output={log_dir}/%x_%A.out
#SBATCH --error={log_dir}/%x_%A.err
#SBATCH --partition={partition}
#SBATCH --ntasks-per-node=1
#SBATCH --cpus-per-task=1
#SBATCH --mem-per-cpu=50G
export PATH=/opt/share/miniconda3/envs/mofmthnn/bin/:$PATH
export LD_LIBRARY_PATH=/opt/share/miniconda3/envs/mofmthnn/lib/:$LD_LIBRARY_PATH

srun python -u {prep_script} --cif_dir {cif_dir} --saved_dir {saved_dir} --cif_list_file {cif_list_file} --n_cpus 1 --suffix {suffix}
"""


# ---------------------------------------------------------------------------
# Functions
# ---------------------------------------------------------------------------

def generate_and_submit_jobs(test_mode: bool) -> None:
    """Generate per-job CIF-list files + SLURM scripts, then submit.

    Mirrors the notebook workflow:
    1. Split sorted CIF list into N_JOBS_TOTAL chunks.
    2. Write each chunk to log_dir/job_{i}_cifs.txt.
    3. Write SLURM script to log_dir/job_{i}_cifs.sh.
    4. Submit (or dry-run) each script.
    """
    log_dir = (
        resolve_output_dir(True, "logs/prep_graph")
        if test_mode
        else LOG_DIR_PROD
    )
    log_dir.mkdir(parents=True, exist_ok=True)
    GRAPH_GRID_DIR.mkdir(parents=True, exist_ok=True)

    # Sort CIF filenames (notebook uses unsorted glob; we sort for reproducibility)
    cifs = [cif.name for cif in sorted(CIF_INPUT_DIR.glob("*.cif"))]
    n_cifs = len(cifs)
    if n_cifs == 0:
        print(f"[WARN] No CIF files found in {CIF_INPUT_DIR}. Skipping.")
        return

    n_jobs = min(N_JOBS_TOTAL, n_cifs)
    n_per_job = n_cifs // n_jobs
    print(f"Preparing {n_cifs} CIFs → {n_jobs} SLURM jobs (~{n_per_job} CIFs each) …")

    script_paths = []
    for i in range(n_jobs):
        start = i * n_per_job
        end = (i + 1) * n_per_job if i < n_jobs - 1 else n_cifs  # last job gets remainder
        job_cifs = cifs[start:end]

        # Write per-job CIF list file
        cif_list_file = log_dir / f"job_{i}_cifs.txt"
        cif_list_file.write_text("\n".join(job_cifs))

        job_name = cif_list_file.stem  # e.g. "job_0_cifs"
        script_content = JOB_TEMPLATE.format(
            job_name=job_name,
            log_dir=log_dir,
            partition=PARTITION,
            prep_script=PREP_SCRIPT,
            cif_dir=CIF_INPUT_DIR,
            saved_dir=GRAPH_GRID_DIR,
            cif_list_file=cif_list_file,
            suffix=job_name,
        )
        script_path = log_dir / f"{job_name}.sh"
        script_path.write_text(script_content)
        script_paths.append(script_path)

    print(f"Generated {len(script_paths)} job scripts + CIF lists in {log_dir}")

    # Submit
    for sp in script_paths:
        sbatch_submit(sp, test_mode=test_mode, cwd=REPO_ROOT)
        if not test_mode:
            time.sleep(0.1)  # avoid flooding the scheduler

    print(f"{'[DRY-RUN] ' if test_mode else ''}All {len(script_paths)} jobs {'echoed' if test_mode else 'submitted'}.")


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(
        description="Exp04: Prepare graph/grid data for GNN models via SLURM."
    )
    add_test_arg(parser)
    args = parser.parse_args()

    generate_and_submit_jobs(test_mode=args.test)

    if args.test:
        print("[TEST MODE] sbatch calls replaced with dry-run echo.")


if __name__ == "__main__":
    main()
