def run_breakthrough(params_df: pd.DataFrame, test: bool) -> None:
    """Run BKT breakthrough simulations."""
    sys.path.insert(0, str(BKT_SRC.parent))
    if test:
        print("[DRY-RUN] would run BKT breakthrough simulations.")
        return
    if not BKT_SRC.exists():
        print("[WARN] BKT src not found; skipping breakthrough simulations.")
        return
    try:
        from bkt.src.batch_simulation import run_batch_simulations
        run_batch_simulations(params_df, output_dir=GCMC_RESULTS_BASE / "bkt_results")
    except (ImportError, Exception) as e:
        print(f"[WARN] Breakthrough simulation failed: {e}")


