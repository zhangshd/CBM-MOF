def parse_gcmc_results(gcmc_dir: Path, test: bool) -> pd.DataFrame:
    """Parse RASPA3 raw outputs using MOF-HTS result parser."""
    sys.path.insert(0, str(MOF_HTS_REPO))
    if test:
        # Return dummy DataFrame with 2 MOFs × 2 gases × 3 pressures = 12 rows
        # (≥2 rows per gas required for plot_rho_distribution KDE)
        return pd.DataFrame({
            "CifId":         ["TEST_MOF_A"] * 6 + ["TEST_MOF_B"] * 6,
            "Gas":           ["CH4", "CH4", "CH4", "N2", "N2", "N2"] * 2,
            "Pressure_Pa":   [1e4, 1e5, 1e6, 1e4, 1e5, 1e6] * 2,
            "Loading_molkg": [1.0, 2.5, 4.0, 0.5, 1.2, 2.0,
                              1.2, 2.8, 4.5, 0.6, 1.4, 2.3],
        })
    try:
        from gcmc.raspa3_result_parser import RASPA3ResultParser
        parser = RASPA3ResultParser(gcmc_dir)
        df = parser.parse_all()
        return df
    except ImportError:
        print("[WARN] raspa3_result_parser not importable; returning empty DataFrame.")
        return pd.DataFrame()


def fit_isotherms(loading_df: pd.DataFrame, out_csv: Path) -> pd.DataFrame:
    """Fit Langmuir / DSLangmuir isotherms and save parameters."""
    if loading_df.empty:
        print("[SKIP] No loading data to fit.")
        return pd.DataFrame()
    try:
        sys.path.insert(0, str(MOF_HTS_REPO))
        from adsorption_analysis.batch_isotherm_fitting import batch_fit
        params_df = batch_fit(loading_df)
    except (ImportError, Exception) as e:
        print(f"[WARN] Isotherm fitting skipped: {e}")
        params_df = loading_df.copy()

    out_csv.parent.mkdir(parents=True, exist_ok=True)
    params_df.to_csv(out_csv, index=False)
    print(f"Isotherm fit params → {out_csv}")
    return params_df


