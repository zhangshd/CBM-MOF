# ---------------------------------------------------------------------------
# SLURM submission
# ---------------------------------------------------------------------------

def submit_isotherm_gcmc(cif_dir: Path, gcmc_out: Path, test: bool) -> None:
    """Submit RASPA3 pure-component isotherm GCMC jobs via MOF-HTS submitter."""
    submitter_script = MOF_HTS_REPO / "gcmc" / "raspa3_batch_slurm_submitter.py"
    config_py = REPO_ROOT / "src" / "experiments" / "_isotherm_gcmc_config.py"

    # Write a temporary config (overwritten each run)
    config_content = f"""\
# Auto-generated by exp09_top_mofs_isotherm.py — do not edit manually
CIF_DIR     = "{cif_dir}"
OUTPUT_DIR  = "{gcmc_out}"
GASES       = ["CH4", "N2"]
PRESSURES   = {CH4_PRESSURES}
TEMPERATURE = 298  # K
N_CYCLES    = 5000
"""
    config_py.write_text(config_content)

    if test:
        print(f"[DRY-RUN] would submit GCMC jobs: sbatch {submitter_script} --config {config_py}")
    else:
        import subprocess
        cmd = ["python", str(submitter_script), "--config", str(config_py)]
        print(f"Submitting: {' '.join(cmd)}")
        subprocess.run(cmd, check=True)


