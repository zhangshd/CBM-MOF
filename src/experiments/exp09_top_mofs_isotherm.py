def plot_rho_distribution(loading_df: pd.DataFrame, full_df: pd.DataFrame,
                           gas: str, fig_dir: Path) -> None:
    """KDE density comparison: full library vs selected MOFs for *gas* loading at 1 bar."""
    import matplotlib.pyplot as plt
    from scipy.stats import gaussian_kde

    if loading_df.empty:
        return
    target_p = 1e5  # 1 bar in Pa
    col = "Loading_molkg"
    gas_col = "Gas"

    sel_vals = loading_df[
        (loading_df[gas_col] == gas) & np.isclose(loading_df["Pressure_Pa"], target_p, rtol=0.05)
    ][col].dropna().values

    # Try to gather full-library distribution from training data
    train_col = f"Ads{gas}_100kPa"
    all_vals = full_df[train_col].dropna().values if train_col in full_df.columns else np.array([])

    if len(sel_vals) < 2:
        print(f"[SKIP] Not enough selected data for rho distribution ({gas}).")
        return

    fig, ax = plt.subplots(figsize=(7, 5))
    x_min, x_max = 0, np.quantile(max(sel_vals, all_vals, key=len), 0.999) if len(all_vals) else sel_vals.max() * 1.2

    for vals, label, color in [
        (all_vals, "Full screened library", NATURE_COLORS["blue"]),
        (sel_vals, "Final selected MOFs", NATURE_COLORS["red"]),
    ]:
        if len(vals) < 2:
            continue
        x_grid = np.linspace(x_min, x_max, 300)
        kde = gaussian_kde(vals, bw_method="scott")
        ax.fill_between(x_grid, kde(x_grid), alpha=0.3, color=color)
        ax.plot(x_grid, kde(x_grid), color=color, linewidth=2, label=label)

    ax.set_xlabel(f"{gas} loading at 1 bar (mol·kg⁻¹)", fontsize=11, fontweight="bold")
    ax.set_ylabel("Kernel Density", fontsize=11, fontweight="bold")
    ax.set_title(f"{gas} Loading Distribution: Library vs Selected", fontsize=12, fontweight="bold", loc="left")
    ax.legend(fontsize=10)
    apply_nature_axes(ax)
    fig.tight_layout()
    savefig(fig, fig_dir / f"exp09_rho_distribution_{gas.lower()}.png")


def plot_isotherm_fits(loading_df: pd.DataFrame, params_df: pd.DataFrame,
                       gas: str, mof_ids: list, fig_dir: Path) -> None:
    """Plot experimental loading + Langmuir fit for each selected MOF."""
    import matplotlib.pyplot as plt

    if loading_df.empty or params_df.empty:
        return

    for mof_id in mof_ids[:5]:          # limit to first 5 to avoid too many figures
        sub = loading_df[(loading_df["CifId"] == mof_id) & (loading_df["Gas"] == gas)]
        if sub.empty:
            continue
        p_vals = sub["Pressure_Pa"].values
        q_vals = sub["Loading_molkg"].values

        fig, ax = plt.subplots(figsize=(5, 4))
        ax.scatter(p_vals / 1e5, q_vals, color=NATURE_COLORS["blue"], s=40, zorder=3,
                   label="GCMC")
        ax.set_xlabel("Pressure (bar)", fontsize=11, fontweight="bold")
        ax.set_ylabel("Loading (mol·kg⁻¹)", fontsize=11, fontweight="bold")
        ax.set_title(f"{mof_id}\n{gas} isotherm", fontsize=11, fontweight="bold", loc="left")
        ax.legend(fontsize=9)
        apply_nature_axes(ax)
        fig.tight_layout()
        savefig(fig, fig_dir / f"exp09_isotherm_fit_{mof_id}_{gas.lower()}.png")


