def main() -> None:
    parser = argparse.ArgumentParser(description="Exp09: Isotherm GCMC for top MOFs.")
    add_test_arg(parser)
    args = parser.parse_args()
    test = args.test

    setup_matplotlib()
    fig_dir = resolve_output_dir(test, "figures")
    gcmc_out = GCMC_RESULTS_BASE if not test else resolve_output_dir(test, "cbm_screening/gcmc_final_selected_ml_org")

    # Determine CIF dir
    cif_dir = FINAL_CIF_DIR if not test else resolve_output_dir(test, "cbm_screening/inference/final_selected_cifs_ml_org")
    if not cif_dir.exists() or not list(cif_dir.glob("*.cif")):
        print(f"[INFO] CIF dir is empty or missing: {cif_dir}. Run exp08 first.")
        if not test:
            return

    # 1. Submit GCMC
    submit_isotherm_gcmc(cif_dir, gcmc_out, test)

    # 2. Parse results
    parsed_csv = gcmc_out / "raspa3_parsed_results.csv"
    if parsed_csv.exists():
        loading_df = pd.read_csv(parsed_csv)
        print(f"Loaded parsed results: {len(loading_df)} rows.")
    else:
        loading_df = parse_gcmc_results(gcmc_out, test)
        if not loading_df.empty:
            parsed_csv.parent.mkdir(parents=True, exist_ok=True)
            loading_df.to_csv(parsed_csv, index=False)
            print(f"Parsed results → {parsed_csv}")

    # 3. Fit isotherms
    params_df = fit_isotherms(loading_df, gcmc_out / "isotherm_params.csv")

    # 4. Breakthrough simulation
    run_breakthrough(params_df, test)

    # 5. Figures — load full library predictions for comparison
    full_pred_csv = REPO_ROOT / "results" / "cbm_screening" / "inference" \
        / "all_batches_predictions_with_separation_metrics_ml.csv"
    full_df = pd.read_csv(full_pred_csv) if full_pred_csv.exists() else pd.DataFrame()

    mof_ids = loading_df["CifId"].unique().tolist() if not loading_df.empty else []
    for gas in ["CH4", "N2"]:
        plot_rho_distribution(loading_df, full_df, gas, fig_dir)
        plot_isotherm_fits(loading_df, params_df, gas, mof_ids, fig_dir)

    if test:
        print("[TEST MODE] All outputs in results/test_run/")


if __name__ == "__main__":
    main()
